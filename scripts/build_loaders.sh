#!/bin/bash
# Assembles scripts/loaders/*.S (needs clang) and regenerates Sources/JupiterFlashCore/BootLoaders.swift.
set -euo pipefail
cd "$(dirname "$0")/.."
TMP="$(mktemp -d)"
for n in mbr fat32; do clang -c -target i386-pc-none-elf "scripts/loaders/$n.S" -o "$TMP/$n.o"; done
python3 -I - "$TMP" Sources/JupiterFlashCore/BootLoaders.swift <<'PY'
import sys, struct
tmp, out = sys.argv[1], sys.argv[2]
def text(name):
    d = open(f"{tmp}/{name}.o", 'rb').read()
    shoff = struct.unpack_from('<I', d, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 0x2E)
    secs = [struct.unpack_from('<IIIIIIIIII', d, shoff + i * shentsize) for i in range(shnum)]
    stroff = secs[shstrndx][4]
    names = {d[stroff + s[0]:d.index(b'\0', stroff + s[0])].decode(): s for s in secs}
    assert '.rel.text' not in names, "relocations present – use absolute constants"
    s = names['.text']; return d[s[4]:s[4] + s[5]]
mbr = text('mbr'); fat = text('fat32')
assert len(mbr) <= 440 and len(fat) == 512 and fat[510:512] == b'\x55\xaa'
mbr = mbr + bytes(440 - len(mbr))
def arr(b): return ",\n        ".join(", ".join(f"0x{x:02X}" for x in b[i:i+16]) for i in range(0, len(b), 16))
open(out, "w").write(f"""// SPDX-License-Identifier: GPL-3.0-or-later
// GENERATED by scripts/build_loaders.sh from scripts/loaders/*.S – do not edit.
import Foundation

/// Jupiter Flasher's own legacy boot code (original work, see scripts/loaders).
enum BootLoaders {{
    /// 440-byte MBR code: finds the active partition and runs its boot sector.
    static let mbrCode: [UInt8] = [
        {arr(mbr)}
    ]
    /// FAT32 boot sector template (BPB left blank). The 11-byte file name to load sits at `nameOffset`.
    static let fat32Sector: [UInt8] = [
        {arr(fat)}
    ]
    static let nameOffset = 0x1F0
}}
""")
print("mbr code bytes:", len(mbr), " fat32 sector:", len(fat))
PY
rm -rf "$TMP"
